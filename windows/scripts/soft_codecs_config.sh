#!/usr/bin/env bash
# soft_codecs_config.sh -- regenerates the configuration files cmake/soft_codecs.cmake builds libvpx
# and dav1d with, by running each project's own configure step once (libvpx's configure script,
# dav1d's meson), so that the Windows build needs neither a POSIX shell nor meson:
#
#   windows/third_party/codecs/libvpx/   vpx_config.h, vpx_config.asm, vpx_config.c, vpx_version.h,
#                                        the run-time CPU dispatch headers (*_rtcd.h) and
#                                        sources.cmake, the library's source list for this
#                                        configuration (its own `make libvpx_srcs.txt`)
#   windows/third_party/codecs/dav1d/    config.h (Windows and other systems in one file),
#                                        config.asm
#
#   windows/scripts/soft_codecs_config.sh [work dir]
#
# Run it after changing a version in cmake/soft_codecs.cmake (the versions and SHA-256 are read
# from there). Needs curl, sha256sum, make, nasm, a C compiler (x86_64-w64-mingw32-gcc for the
# Windows half of dav1d's configuration, gcc for the rest) and meson.
#
# The configuration: decoders only (no VP8/VP9 encoder, no postprocessing, no examples or tools);
# x86-64 SIMD with run-time CPU detection (SSE2 up to AVX2; libvpx's AVX-512 left out: none of
# its decoder functions use it); VP9 profiles 2 and 3 (10 and 12-bit); a decoder size limit of
# 8192x8192, so that a corrupt header cannot make it allocate more. dav1d: 8 and 16-bit (10 and
# 12-bit) pixels, its assembly, the C functions the assembly always replaces left out
# (trim_dsp), no logging.

set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
win=$(cd "$here/.." && pwd)
cmake_file="$win/cmake/soft_codecs.cmake"
work=${1:-$(mktemp -d)}
mkdir -p "$work"

pin() { sed -n "s/^set($1 \\([^ )]*\\)).*/\\1/p" "$cmake_file"; }
vpx_version=$(pin WINAPK_VPX_VERSION)
vpx_sha=$(pin WINAPK_VPX_SHA256)
dav1d_version=$(pin WINAPK_DAV1D_VERSION)
dav1d_sha=$(pin WINAPK_DAV1D_SHA256)

fetch() {  # url file sha256
    if [ ! -f "$work/$2" ]; then curl -fsSL -o "$work/$2" "$1"; fi
    echo "$3  $work/$2" | sha256sum -c --quiet -
}
fetch "https://storage.googleapis.com/downloads.webmproject.org/releases/webm/libvpx-$vpx_version.tar.gz" \
      "libvpx-$vpx_version.tar.gz" "$vpx_sha"
fetch "https://downloads.videolan.org/pub/videolan/dav1d/$dav1d_version/dav1d-$dav1d_version.tar.xz" \
      "dav1d-$dav1d_version.tar.xz" "$dav1d_sha"
tar -C "$work" -xzf "$work/libvpx-$vpx_version.tar.gz"
tar -C "$work" -xJf "$work/dav1d-$dav1d_version.tar.xz"

# ---- libvpx ----------------------------------------------------------------------------------
# The configuration is the same for Windows and Linux on x86-64 (the code itself asks _WIN32), so
# configuring for one target serves both; the assembler's object format is cmake's choice.
vpx_src="$work/libvpx-$vpx_version"
vpx_build="$work/vpx-build"
rm -rf "$vpx_build" && mkdir -p "$vpx_build"
(cd "$vpx_build" && "$vpx_src/configure" --target=x86_64-linux-gcc --as=nasm --enable-runtime-cpu-detect \
    --enable-vp9-highbitdepth --disable-vp8-encoder --disable-vp9-encoder --disable-postproc \
    --disable-vp9-postproc --disable-examples --disable-tools --disable-docs --disable-unit-tests \
    --disable-install-docs --disable-install-bins --disable-install-libs --disable-install-srcs \
    --disable-libyuv --disable-webm-io --disable-avx512 --size-limit=8192x8192 > configure.log &&
    make libvpx_srcs.txt > /dev/null)
out="$win/third_party/codecs/libvpx"
rm -rf "$out" && mkdir -p "$out"
cp "$vpx_build"/{vpx_config.h,vpx_config.asm,vpx_config.c,vpx_version.h,vp8_rtcd.h,vp9_rtcd.h,vpx_dsp_rtcd.h,vpx_scale_rtcd.h} "$out/"
{
    echo "# Generated by windows/scripts/soft_codecs_config.sh from libvpx $vpx_version's own source list"
    echo "# (make libvpx_srcs.txt) for the configuration that script describes. Do not edit."
    echo "set(WINAPK_VPX_C_SOURCES"
    grep -E '\.c$' "$vpx_build/libvpx_srcs.txt" | grep -v '^vpx_config\.c$' | sed 's/^/  /'
    echo ")"
    echo "set(WINAPK_VPX_ASM_SOURCES"
    grep -E '\.asm$' "$vpx_build/libvpx_srcs.txt" | grep -v 'x86_abi_support\.asm$' | sed 's/^/  /'
    echo ")"
} > "$out/sources.cmake"

# ---- dav1d -----------------------------------------------------------------------------------
dav1d_src="$work/dav1d-$dav1d_version"
cross="$work/mingw.cross"
cat > "$cross" <<'EOF'
[binaries]
c = 'x86_64-w64-mingw32-gcc'
ar = 'x86_64-w64-mingw32-ar'
strip = 'x86_64-w64-mingw32-strip'
windres = 'x86_64-w64-mingw32-windres'
nasm = 'nasm'
[host_machine]
system = 'windows'
cpu_family = 'x86_64'
cpu = 'x86_64'
endian = 'little'
EOF
opts=(-Dbitdepths=8,16 -Denable_asm=true -Denable_tools=false -Denable_examples=false -Denable_tests=false
      -Denable_docs=false -Dlogging=false -Dtrim_dsp=true -Ddefault_library=static)
rm -rf "$work/dav1d-win" "$work/dav1d-other"
meson setup "${opts[@]}" --cross-file "$cross" "$work/dav1d-win" "$dav1d_src" > /dev/null
meson setup "${opts[@]}" "$work/dav1d-other" "$dav1d_src" > /dev/null
cmp "$work/dav1d-win/config.asm" "$work/dav1d-other/config.asm"
out="$win/third_party/codecs/dav1d"
rm -rf "$out" && mkdir -p "$out"
cp "$work/dav1d-win/config.asm" "$out/config.asm"
# One config.h: the lines both configurations share, then each one's own under _WIN32.
python3 - "$work/dav1d-win/config.h" "$work/dav1d-other/config.h" "$out/config.h" "$dav1d_version" <<'EOF'
import sys
def defines(path):
    return [l.rstrip("\n") for l in open(path) if l.startswith("#define ")]
win, other = defines(sys.argv[1]), defines(sys.argv[2])
common = [l for l in win if l in other]
with open(sys.argv[3], "w") as f:
    f.write("/* Generated by windows/scripts/soft_codecs_config.sh from dav1d %s's meson configuration,\n"
            " * for Windows (MinGW) and for other x86-64 systems. Do not edit. */\n\n#pragma once\n\n" % sys.argv[4])
    f.write("\n".join(common) + "\n\n#ifdef _WIN32\n")
    f.write("\n".join(l for l in win if l not in common) + "\n#else\n")
    f.write("\n".join(l for l in other if l not in common) + "\n#endif\n")
EOF
echo "regenerated windows/third_party/codecs/{libvpx,dav1d} from libvpx $vpx_version and dav1d $dav1d_version"
