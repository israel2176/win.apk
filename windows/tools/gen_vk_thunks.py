#!/usr/bin/env python3
"""gen_vk_thunks.py -- writes host/vk/guest_vk_table.inc and host/vk/guest_vk.inc from
third_party/khronos/vulkan/vulkan_core.h.

An app's native code calls Vulkan with the System V calling convention; the PC's Vulkan
(vulkan-1.dll, the Khronos loader, and the GPU's driver behind it) is Microsoft x64. For every
command vulkan_core.h declares, guest_vk.inc has:

  - (guest_vk_table.inc) a member of VkTable, the command's function pointer as the loader gives it for one instance
    or one device (vk_fill_instance / vk_fill_device);
  - (guest_vk.inc) unless host/vk/guest_vk.cpp writes it by hand (OVERRIDES below), a WINAPK_GUEST_ABI wrapper
    that calls the table of the dispatchable handle it is given (its first parameter; table_of in
    guest_vk.cpp), passing a null pAllocator: the app's allocation callbacks are System V
    functions the driver cannot call, and null is always allowed (the implementation allocates);
  - an entry in kGuestVk: the name, the wrapper, and whether it is a device-level command (its
    first parameter a VkDevice, VkQueue or VkCommandBuffer), for vkGet*ProcAddr and the guest
    linker.

Struct layouts need no translation: Vulkan's types are fixed-size integers, floats and pointers,
the same on Linux x86_64 and Windows x64 (no `long` anywhere in the API).

    windows/tools/gen_vk_thunks.py   (rewrites both files)
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.join(HERE, "..", "third_party", "khronos", "vulkan", "vulkan_core.h")
OUT = os.path.join(HERE, "..", "host", "vk", "guest_vk.inc")
TABLE_OUT = os.path.join(HERE, "..", "host", "vk", "guest_vk_table.inc")

# Written by hand in guest_vk.cpp: the global commands, the ones that create or describe what the
# app sees (instances, devices, extensions, versions, debug callbacks), and the window system's
# (surfaces, swapchains), which guest_vk.cpp emulates on images it reads back.
OVERRIDES = {
    "vkCreateInstance", "vkDestroyInstance", "vkEnumerateInstanceExtensionProperties",
    "vkEnumerateInstanceLayerProperties", "vkEnumerateInstanceVersion", "vkGetInstanceProcAddr",
    "vkGetDeviceProcAddr", "vkEnumeratePhysicalDevices", "vkEnumeratePhysicalDeviceGroups",
    "vkEnumeratePhysicalDeviceGroupsKHR", "vkGetPhysicalDeviceProperties", "vkGetPhysicalDeviceProperties2",
    "vkGetPhysicalDeviceProperties2KHR", "vkEnumerateDeviceExtensionProperties",
    "vkEnumerateDeviceLayerProperties", "vkCreateDevice", "vkDestroyDevice", "vkGetDeviceQueue",
    "vkGetDeviceQueue2", "vkAllocateCommandBuffers",
    "vkCreateDebugUtilsMessengerEXT", "vkDestroyDebugUtilsMessengerEXT", "vkCreateDebugReportCallbackEXT",
    "vkDestroyDebugReportCallbackEXT",
    # VK_KHR_surface, VK_KHR_get_surface_capabilities2, VK_KHR_swapchain (and its device-group part).
    "vkDestroySurfaceKHR", "vkGetPhysicalDeviceSurfaceSupportKHR", "vkGetPhysicalDeviceSurfaceCapabilitiesKHR",
    "vkGetPhysicalDeviceSurfaceFormatsKHR", "vkGetPhysicalDeviceSurfacePresentModesKHR",
    "vkGetPhysicalDeviceSurfaceCapabilities2KHR", "vkGetPhysicalDeviceSurfaceFormats2KHR",
    "vkCreateSwapchainKHR", "vkDestroySwapchainKHR", "vkGetSwapchainImagesKHR", "vkAcquireNextImageKHR",
    "vkQueuePresentKHR", "vkAcquireNextImage2KHR", "vkGetDeviceGroupPresentCapabilitiesKHR",
    "vkGetDeviceGroupSurfacePresentModesKHR", "vkGetPhysicalDevicePresentRectanglesKHR",
}

DEVICE_HANDLES = {"VkDevice", "VkQueue", "VkCommandBuffer"}
INSTANCE_HANDLES = {"VkInstance", "VkPhysicalDevice"}


def commands():
    text = open(CORE, encoding="utf-8").read()
    out = []
    for m in re.finditer(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);", text, re.S):
        ret, name, params = m.group(1).strip(), m.group(2), " ".join(m.group(3).split())
        if params == "void":
            params = ""
        out.append((ret, name, params))
    seen, unique = set(), []
    for c in out:
        if c[1] not in seen:
            seen.add(c[1])
            unique.append(c)
    return unique


def split_params(params):
    """[(declaration, name, type)] of a C parameter list (no function pointers in Vulkan's)."""
    result = []
    for p in [x.strip() for x in params.split(",") if x.strip()]:
        m = re.match(r"(.*?)(\w+)(\s*\[\s*\w*\s*\])?$", p)
        decl_type, pname, array = m.group(1).strip(), m.group(2), m.group(3) or ""
        base = decl_type.replace("const", "").replace("*", "").strip()
        result.append((p, pname, base, array))
    return result


def main():
    cmds = commands()
    header = "// GENERATED by windows/tools/gen_vk_thunks.py from third_party/khronos/vulkan/vulkan_core.h. Do not edit."
    lines = [
        header,
        "// The PC's Vulkan commands, one table per instance and per device (guest_vk.cpp).",
        "",
        "struct VkTable {",
    ]
    for ret, name, params in cmds:
        lines.append(f"    PFN_{name} {name} = nullptr;")
    lines.append("};")
    lines.append("")

    fill_instance, fill_device, wrappers, entries = [], [], [], []
    for ret, name, params in cmds:
        ps = split_params(params)
        first = ps[0][2] if ps else None
        if first in INSTANCE_HANDLES or first in DEVICE_HANDLES:
            fill_instance.append(f"    t.{name} = reinterpret_cast<PFN_{name}>(gipa(instance, \"{name}\"));")
        if first in DEVICE_HANDLES:
            fill_device.append(f"    if (auto p = gdpa(device, \"{name}\")) t.{name} = reinterpret_cast<PFN_{name}>(p);")
        device = "true" if first in DEVICE_HANDLES else "false"
        if name in OVERRIDES:
            entries.append(f"    {{\"{name}\", reinterpret_cast<void*>(&guest_{name}), {device}}},")
            continue
        if first not in INSTANCE_HANDLES and first not in DEVICE_HANDLES:
            continue  # a global command not written by hand: none in Vulkan 1.3
        # The allocator is not passed on: its parameter keeps its type and loses its name.
        decl = ", ".join(p[0][: -len(p[1])].rstrip() if p[1] == "pAllocator" else p[0] for p in ps)
        args = ", ".join("nullptr" if p[1] == "pAllocator" else p[1] for p in ps)
        call = f"table_of({ps[0][1]}).{name}"
        if ret == "void":
            body = f"    if (auto f = {call}) f({args});"
        else:
            missing = "VK_ERROR_EXTENSION_NOT_PRESENT" if ret == "VkResult" else f"{ret}{{}}"
            body = f"    if (auto f = {call}) return f({args});\n    return {missing};"
        wrappers.append(f"WINAPK_GUEST_ABI {ret} guest_{name}({decl}) {{\n{body}\n}}")
        entries.append(f"    {{\"{name}\", reinterpret_cast<void*>(&guest_{name}), {device}}},")

    lines.append("// Every command of the instance (and, through the loader's trampolines, of its devices).")
    lines.append("void vk_fill_instance(VkTable& t, VkInstance instance, PFN_vkGetInstanceProcAddr gipa) {")
    lines += fill_instance
    lines.append("}")
    lines.append("")
    lines.append("// A device's own commands, straight to its driver.")
    lines.append("void vk_fill_device(VkTable& t, VkDevice device, PFN_vkGetDeviceProcAddr gdpa) {")
    lines += fill_device
    lines.append("}")
    lines.append("")
    table_lines = lines
    lines = [header, "// The Vulkan commands an app's native code calls, System V side (guest_vk.cpp).", ""]
    lines += wrappers
    lines.append("")
    lines.append("struct GuestVkCommand {")
    lines.append("    const char* name;")
    lines.append("    void* fn;")
    lines.append("    bool device;  // a device-level command: vkGetDeviceProcAddr answers it")
    lines.append("};")
    lines.append("const GuestVkCommand kGuestVk[] = {")
    lines += entries
    lines.append("};")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(TABLE_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(table_lines) + "\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{OUT}: {len(cmds)} commands, {len(wrappers)} generated wrappers, {len(OVERRIDES)} by hand")


if __name__ == "__main__":
    main()
